"""Turn the A2-Lite submodel of a NAM Core example model into hosts/daisy/nam/a2lite_weights.hpp.

    hosts/daisy/tools/fetch-nam-model
    hosts/daisy/tools/nam_to_header.py build/nam-model/A2.nam > hosts/daisy/nam/a2lite_weights.hpp

The input is NeuralAmpModelerCore's own example model (MIT licence, notice in hosts/daisy/THIRD_PARTY.md):
a SlimmableContainer whose first submodel (max_value 0.5) is the 3-channel A2-Lite. The weights are written as float literals that round-trip (9 significant digits) in
NAM Core's reading order, which a2lite.hpp documents. Standard library only.
"""
import json
import struct
import sys

KS = [6] * 14 + [15, 15] + [6] * 7
HEAD_K = 16


def main() -> int:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    d = json.load(open(sys.argv[1]))
    if d["architecture"] != "SlimmableContainer":
        sys.exit("expected a SlimmableContainer")
    sub = min(d["config"]["submodels"], key=lambda s: s["max_value"])
    m = sub["model"]
    ch = m["config"]["layers"][0]["channels"]
    w = m["weights"]
    expect = ch + sum(ch * ch * k + ch + ch + ch * ch + ch for k in KS) + ch * HEAD_K + 2
    if ch != 3 or len(w) != expect or m["config"]["layers"][0]["kernel_sizes"] != KS:
        sys.exit(f"not the A2-Lite shape: {ch} channels, {len(w)} weights (want {expect})")
    f32 = [struct.unpack("f", struct.pack("f", x))[0] for x in w]
    print("// SPDX-License-Identifier: MIT")
    print("// GENERATED by hosts/daisy/tools/nam_to_header.py - do not edit. The A2-Lite submodel (3 channels, 23 layers,")
    print(f"// {len(w)} weights) of NeuralAmpModelerCore's example A2 model (MIT, Steven Atkinson), in NAM Core's order.")
    print("#pragma once")
    print("namespace squatch::nam {")
    print(f"constexpr int kA2LiteWeightCount = {len(w)};")
    print("constexpr float kA2LiteWeights[kA2LiteWeightCount] = {")
    for i in range(0, len(f32), 6):
        print("    " + ", ".join(f"{x:.9g}f" for x in f32[i:i + 6]) + ",")
    print("};")
    print("}  // namespace squatch::nam")
    return 0


if __name__ == "__main__":
    sys.exit(main())
